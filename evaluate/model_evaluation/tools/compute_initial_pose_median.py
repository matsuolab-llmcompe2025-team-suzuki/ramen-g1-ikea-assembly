"""Compute per-joint median of frame-0 action.robot_q_desired for a task_index.

issue-70-flip-table-data-augmentation の SubtaskStartPose 決定方法と同等の
実測値算出 script。指定 task_index について、各 training episode の該当 task 初出
frame の action.robot_q_desired[22:36] (arm 14D) と action.hand_cmd (2D) を集めて
per-joint median を出す。

# 使い方

```bash
cd iros_2026_ramen/model/ramen_ori   # pyarrow + huggingface_hub がある env
pixi run python -m evaluate.model_evaluation.tools.compute_initial_pose_median \\
    --dataset BitRobot/G1_WBT_Dex1_Building-Children-Table \\
    --task-index 5 \\
    --task-label "rotate table base" \\
    --local-dir /tmp/g1_wbt_data \\
    --output /tmp/rotate_table_base_initial_pose.yaml
```

出力は skill_config.yaml の initial_pose section にそのまま貼り付けられる YAML。
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Iterable

import numpy as np
import pyarrow.parquet as pq


ARM_SLICE = slice(22, 36)  # G1 36D action layout: root7 + legs12 + waist3 + arms14
HAND_DEX1_OPEN_MAX_RAD = 4.5


def _iter_data_parquets(root: Path) -> Iterable[Path]:
    """Yield every data/chunk-*/file-*.parquet in the snapshot root."""
    data_root = root / "data"
    if not data_root.exists():
        raise FileNotFoundError(f"no data/ dir in snapshot: {data_root}")
    for chunk_dir in sorted(data_root.glob("chunk-*")):
        for parquet in sorted(chunk_dir.glob("file-*.parquet")):
            yield parquet


def _first_frame_row_per_episode(
    parquets: Iterable[Path], task_index: int
) -> list[dict]:
    """Return per-episode first-frame row where task_index matches."""
    seen_episodes: dict[int, dict] = {}
    for parquet in parquets:
        table = pq.read_table(
            parquet,
            columns=[
                "episode_index",
                "frame_index",
                "task_index",
                "action.robot_q_desired",
                "action.hand_cmd",
            ],
        )
        df = table.to_pandas()
        match = df[df["task_index"] == task_index]
        if match.empty:
            continue
        # per-episode の最小 frame_index を取る
        idx = match.groupby("episode_index")["frame_index"].idxmin()
        first_rows = match.loc[idx]
        for _, row in first_rows.iterrows():
            ep = int(row["episode_index"])
            if ep not in seen_episodes:
                seen_episodes[ep] = {
                    "episode_index": ep,
                    "frame_index": int(row["frame_index"]),
                    "action_robot_q_desired": np.asarray(
                        row["action.robot_q_desired"], dtype=np.float64
                    ),
                    "action_hand_cmd": np.asarray(
                        row["action.hand_cmd"], dtype=np.float64
                    ),
                }
            else:
                # 同 episode で複数 file にまたがる場合、frame_index が小さい方を優先
                if int(row["frame_index"]) < seen_episodes[ep]["frame_index"]:
                    seen_episodes[ep] = {
                        "episode_index": ep,
                        "frame_index": int(row["frame_index"]),
                        "action_robot_q_desired": np.asarray(
                            row["action.robot_q_desired"], dtype=np.float64
                        ),
                        "action_hand_cmd": np.asarray(
                            row["action.hand_cmd"], dtype=np.float64
                        ),
                    }
    return sorted(seen_episodes.values(), key=lambda x: x["episode_index"])


def _compute_median(rows: list[dict]) -> tuple[np.ndarray, np.ndarray]:
    """Return (arm14 median, dex1_opening_fraction median [0,1])."""
    if not rows:
        raise RuntimeError("no episodes contained the requested task_index")
    arm_stack = np.stack([r["action_robot_q_desired"][ARM_SLICE] for r in rows])
    hand_stack = np.stack([r["action_hand_cmd"] for r in rows])
    arm_median = np.median(arm_stack, axis=0)
    hand_median_rad = np.median(hand_stack, axis=0)
    # issue-70 と同じ conversion: physical rad / 4.5 = opening fraction [0,1]
    hand_opening = np.clip(hand_median_rad / HAND_DEX1_OPEN_MAX_RAD, 0.0, 1.0)
    return arm_median, hand_opening


G1_ARM_JOINT_NAMES = (
    "L.shoulder_pitch", "L.shoulder_roll", "L.shoulder_yaw",
    "L.elbow", "L.wrist_roll", "L.wrist_pitch", "L.wrist_yaw",
    "R.shoulder_pitch", "R.shoulder_roll", "R.shoulder_yaw",
    "R.elbow", "R.wrist_roll", "R.wrist_pitch", "R.wrist_yaw",
)


def _emit_yaml(
    skill_name: str,
    task_index: int,
    task_label: str,
    dataset_repo_id: str,
    dataset_revision: str,
    training_episode_count: int,
    arm_median: np.ndarray,
    hand_opening: np.ndarray,
) -> str:
    """Emit a skill_config.yaml initial_pose section as YAML text."""
    lines = [
        f"  # ---- Auto-generated by compute_initial_pose_median.py ----",
        f"  # dataset: {dataset_repo_id}@{dataset_revision}",
        f"  # task_index: {task_index} ({task_label})",
        f"  # training_episode_count: {training_episode_count}",
        f"  # statistic: median_action_robot_q_desired_frame0_arms14;"
        f"median_action_hand_cmd_frame0_dex1_2",
        f"  {skill_name}:",
        f"    initial_pose:",
        f"      arm_position_rad:",
    ]
    for name, value in zip(G1_ARM_JOINT_NAMES, arm_median):
        lines.append(f"        {name}: {float(value):.10f}")
    lines.append(f"      dex1_opening_fraction:")
    lines.append(f"        left:  {float(hand_opening[0]):.10f}")
    lines.append(f"        right: {float(hand_opening[1]):.10f}")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--dataset",
        default="BitRobot/G1_WBT_Dex1_Building-Children-Table",
        help="HF dataset repo id",
    )
    ap.add_argument("--revision", default=None, help="pin commit SHA (optional)")
    ap.add_argument("--task-index", type=int, required=True)
    ap.add_argument("--task-label", required=True, help="human-readable task name")
    ap.add_argument("--skill-name", required=True, help="skill_config.yaml key")
    ap.add_argument(
        "--local-dir",
        type=Path,
        required=True,
        help="local snapshot dir (created if missing)",
    )
    ap.add_argument(
        "--output",
        type=Path,
        required=True,
        help="output YAML fragment path",
    )
    ap.add_argument("--skip-download", action="store_true")
    args = ap.parse_args()

    if not args.skip_download:
        print(f"[dl] fetching {args.dataset} data parquets to {args.local_dir}")
        from huggingface_hub import snapshot_download
        snapshot_path = snapshot_download(
            args.dataset,
            repo_type="dataset",
            revision=args.revision,
            allow_patterns=["data/**/*.parquet", "meta/**"],
            local_dir=str(args.local_dir),
        )
    else:
        snapshot_path = str(args.local_dir)
    snapshot_root = Path(snapshot_path)

    # resolve dataset revision (if not pinned)
    revision = args.revision
    if revision is None:
        from huggingface_hub import HfApi
        api = HfApi()
        info = api.dataset_info(args.dataset)
        revision = info.sha

    print(f"[scan] task_index={args.task_index} ({args.task_label!r})")
    rows = _first_frame_row_per_episode(
        _iter_data_parquets(snapshot_root), args.task_index
    )
    print(f"[scan] found {len(rows)} episodes containing task_index={args.task_index}")

    arm_median, hand_opening = _compute_median(rows)
    print(f"[median] arm14 rad range: min={arm_median.min():+.4f} max={arm_median.max():+.4f}")
    print(f"[median] dex1 opening fraction: left={hand_opening[0]:.4f}, right={hand_opening[1]:.4f}")

    yaml_fragment = _emit_yaml(
        skill_name=args.skill_name,
        task_index=args.task_index,
        task_label=args.task_label,
        dataset_repo_id=args.dataset,
        dataset_revision=revision,
        training_episode_count=len(rows),
        arm_median=arm_median,
        hand_opening=hand_opening,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(yaml_fragment, encoding="utf-8")
    print(f"[out] {args.output}")
    print()
    print(yaml_fragment)


if __name__ == "__main__":
    main()
